/** 沿边线性插值零点（`isolevel` 恒为 0，标量场约定负=内部/正=外部）。 */
function interpolateEdge(
  pa: Vec3, pb: Vec3, va: number, vb: number,
): Vec3 {
  const denom = va - vb;
  // 两端值几乎相等（边几乎与等值面平行）：退化取中点，避免除零/数值爆炸。
  const t = Math.abs(denom) < 1e-12 ? 0.5 : va / denom;
  const ct = Math.min(1, Math.max(0, t));
  return [
    pa[0] + ct * (pb[0] - pa[0]),
    pa[1] + ct * (pb[1] - pa[1]),
    pa[2] + ct * (pb[2] - pa[2]),
  ];
}

export interface MarchingCubesOptions {
  readonly bounds: SdfBounds;
  /** 每轴的体素分辨率（cell 数）；网格角点数 = resolution+1。 */
  readonly resolution: number;
}

/**
 * 在 `bounds` 内按 `resolution` 采样 `sample`，跑标准 Marching Cubes，返回去重后的
 * 三角网格。顶点去重用"网格角点对（边）→ 顶点下标"的 Map 缓存（类似 `rock.ts`
 * `subdivide()` 的 midpoint 缓存思路），保证共享边的相邻 cube 复用同一个插值顶点，
 * 不产生缝合缝隙。
 */
export function marchingCubes(sample: SdfSampleFn, options: MarchingCubesOptions): MeshGeometry {
  const { bounds, resolution } = options;
  const res = Math.round(resolution);
  if (!Number.isFinite(res) || res < 2) {
    throw new BakerError(`marchingCubes: resolution must be an integer ≥ 2 (got ${resolution})`);
  }
  const dims: Vec3 = [
    bounds.max[0] - bounds.min[0],
    bounds.max[1] - bounds.min[1],
    bounds.max[2] - bounds.min[2],
  ];
  if (!dims.every((d) => Number.isFinite(d) && d > 1e-9)) {
    throw new BakerError('marchingCubes: bounds must have positive finite extent on every axis');
  }
  const cellSize: Vec3 = [dims[0] / res, dims[1] / res, dims[2] / res];
  const cornersPerAxis = res + 1;

  // 角点标量场缓存：一次性把 (res+1)^3 个角点的采样值算出来，相邻 cube 复用，
  // 避免同一角点被 8 个共享它的 cube 各采样一次（O(resolution^3) 而不是 O(resolution^3 * 8)）。
  const cornerValue = new Float64Array(cornersPerAxis * cornersPerAxis * cornersPerAxis);
  const cornerFlat = (cx: number, cy: number, cz: number): number =>
    (cz * cornersPerAxis + cy) * cornersPerAxis + cx;
  const cornerPos = (cx: number, cy: number, cz: number): Vec3 => [
    bounds.min[0] + cx * cellSize[0],
    bounds.min[1] + cy * cellSize[1],
    bounds.min[2] + cz * cellSize[2],
  ];
  for (let cz = 0; cz < cornersPerAxis; cz += 1) {
    for (let cy = 0; cy < cornersPerAxis; cy += 1) {
      for (let cx = 0; cx < cornersPerAxis; cx += 1) {
        const [x, y, z] = cornerPos(cx, cy, cz);
        cornerValue[cornerFlat(cx, cy, cz)] = sample(x, y, z);
      }
    }
  }

  const vertices: [number, number, number][] = [];
  const faces: [number, number, number][] = [];
  // key = min(flatA,flatB) * totalCorners + max(flatA,flatB) —— 全局网格边的去重键。
  const totalCorners = cornersPerAxis * cornersPerAxis * cornersPerAxis;
  const edgeVertexCache = new Map<number, number>();

  const vertexForEdge = (
    flatA: number, flatB: number, posA: Vec3, posB: Vec3, valA: number, valB: number,
  ): number => {
    const key = flatA < flatB ? flatA * totalCorners + flatB : flatB * totalCorners + flatA;
    const cached = edgeVertexCache.get(key);
    if (cached !== undefined) return cached;
    const p = interpolateEdge(posA, posB, valA, valB);
    const idx = vertices.length;
    vertices.push([p[0], p[1], p[2]]);
    edgeVertexCache.set(key, idx);
    return idx;
  };

  for (let iz = 0; iz < res; iz += 1) {
    for (let iy = 0; iy < res; iy += 1) {
      for (let ix = 0; ix < res; ix += 1) {
        // 8 个角点的网格坐标 + 标量值。
        const cornerGrid: [number, number, number][] = CORNER_OFFSETS.map(
          ([dx, dy, dz]) => [ix + dx, iy + dy, iz + dz],
        );
        const cornerVal = cornerGrid.map(([cx, cy, cz]) => cornerValue[cornerFlat(cx, cy, cz)]);

        let cubeIndex = 0;
        for (let c = 0; c < 8; c += 1) {
          if (cornerVal[c] < 0) cubeIndex |= 1 << c;
        }
        if (cubeIndex === 0 || cubeIndex === 255) continue; // 完全在内部/外部，无三角形

        const tri = TRI_TABLE[cubeIndex];
        // 每条边按需插值一次，同一 cube 内多个三角形共享同一条边的结果。
        const edgeVertexOfCube = new Map<number, number>();
        const vertexForCubeEdge = (edge: number): number => {
          const cached = edgeVertexOfCube.get(edge);
          if (cached !== undefined) return cached;
          const [ca, cb] = EDGE_CORNERS[edge];
          const [gax, gay, gaz] = cornerGrid[ca];
          const [gbx, gby, gbz] = cornerGrid[cb];
          const flatA = cornerFlat(gax, gay, gaz);
          const flatB = cornerFlat(gbx, gby, gbz);
          const idx = vertexForEdge(
            flatA, flatB,
            cornerPos(gax, gay, gaz), cornerPos(gbx, gby, gbz),
            cornerVal[ca], cornerVal[cb],
          );
          edgeVertexOfCube.set(edge, idx);
          return idx;
        };

        for (let i = 0; tri[i] !== -1; i += 3) {
          const a = vertexForCubeEdge(tri[i]);
          const b = vertexForCubeEdge(tri[i + 1]);
          const c = vertexForCubeEdge(tri[i + 2]);
          faces.push([a, b, c]);
        }
      }
    }
  }

  return { kind: 'mesh_geometry', vertices, faces };
}
